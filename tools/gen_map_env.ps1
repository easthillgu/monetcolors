# ============================================================
# gen_map_env.ps1 — 从 game_palette_v1.json 生成 MonetColorMapData-1.0.lua
# game_palette_v1.json 是唯一数据源（extract_game_palette_v1.ps1 产出），
# 本脚本把每个区域的 env HSL 转成 LibMonetColor 可查表的 Lua 数据模块。
# 新增截图/区域后: 重跑取色脚本 -> 重跑本脚本 -> 重跑 test_map_sampler.lua
# ============================================================
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)  # repo root (script lives in tools/)

$srcPath = Join-Path $root "data\game_palette_v1.json"
$outPath = Join-Path $root "MonetColorMapData-1.0.lua"

$data = Get-Content $srcPath -Raw -Encoding UTF8 | ConvertFrom-Json
if (-not $data -or $data.Count -eq 0) { throw "No zones found in data/game_palette_v1.json" }

# 按 mapID 升序输出
$sorted = $data | Sort-Object { [int]$_.mapID }

$lines = [System.Text.StringBuilder]::new()
foreach ($z in $sorted) {
    $name = [string]$z.zone
    $mapID = [int]$z.mapID
    $h = [double]$z.env.h
    $s = [double]$z.env.s
    $l = [double]$z.env.l
    [void]$lines.AppendLine(("    [{0}] = {{ name = '{1}', h = {2}, s = {3}, l = {4} }}," -f $mapID, $name, $h.ToString([cultureinfo]::InvariantCulture), $s.ToString([cultureinfo]::InvariantCulture), $l.ToString([cultureinfo]::InvariantCulture)))
}

$fileCount = (@(Get-ChildItem (Join-Path $root "Gamepics") -Filter *.jpg -ErrorAction SilentlyContinue)).Count
$date = Get-Date -Format "yyyy-MM-dd"

$content = @"
-- MonetColorMapData-1.0.lua
-- WoW map environment color data for LibMonetColor-1.0 (Phase 2 / T2.1).
-- AUTO-GENERATED by tools/gen_map_env.ps1 from data/game_palette_v1.json -- do not edit by hand.
--
-- Source: $fileCount screenshots in Gamepics/ ($($data.Count) zones; game + trip mix),
--   generated $date with pct-weighted environment colors (circular mean hue).
-- Load order does not matter: LibMonetColor looks this module up lazily via
--   LibStub("MonetColorMapData-1.0") or the global LibMonetColorMapData.
--
-- MapEnv: mapID -> { name, h, s, l }
--   h in [0,360]; s, l in [0,1]; classic-era mapIDs (wuxianwow atlas space).

local MAJOR, MINOR = "MonetColorMapData-1.0", 10000

local LibStub = _G.LibStub
local MDM
if type(LibStub) == "table" and LibStub.NewLibrary then
    MDM = LibStub:NewLibrary(MAJOR, MINOR)
    if not MDM then return end
else
    -- Not in WoW (tests / tooling): work on a bare table.
    MDM = {}
end

MDM.Version = MINOR
MDM.Source = "data/game_palette_v1.json"

-- $fileCount screenshots / $($data.Count) zones, generated $date
MDM.MapEnv = {
$($lines.ToString().TrimEnd())
}

-- Global alias so LibMonetColor can find the data even without LibStub.
_G.LibMonetColorMapData = MDM
"@

[System.IO.File]::WriteAllText($outPath, $content, [System.Text.UTF8Encoding]::new($false))
Write-Host "Saved: $outPath ($($data.Count) zones)"
